"""Generate firmware/lite/arm_graph.h from config/vehicle.json geometry.arm (N1, M3 review).

The firmware keeps its own copy of the swept pose graph so it can refuse any arm motion off the edges the
CAD checked, whatever the MacBook sends. `python3 tools/gen_arm_graph.py` rewrites the header;
tests/check_lite_gateway.py fails when the header and config disagree.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HEADER = ROOT / "firmware/lite/arm_graph.h"


def render(config):
    arm = config["geometry"]["arm"]
    names = list(arm["poses_deg"])
    index = {name: k for k, name in enumerate(names)}
    rows = ",\n".join("    {" + ", ".join(str(round(v * 100)) for v in arm["poses_deg"][n]) + "}" for n in names)
    edges = ", ".join(f"{{{index[a]}, {index[b]}}}" for a, b in arm["pose_edges"])
    enum = ", ".join(f"UGV_ARM_{n.upper()} = {k}" for k, n in enumerate(names))
    mask = sum(1 << index[n] for n in arm["drive_poses"])
    return f"""/* Generated by tools/gen_arm_graph.py from config/vehicle.json geometry.arm: do not edit. */
#ifndef UGV_ARM_GRAPH_H
#define UGV_ARM_GRAPH_H

#include <stdint.h>

/* Poses in config order; joints [shoulder, twist, elbow, wrist, roll] in centi-degrees (servo_control.h). */
enum {{ {enum} }};
enum {{ UGV_ARM_JOINTS = {len(arm["joints"])}, UGV_ARM_POSES = {len(names)}, UGV_ARM_EDGES = {len(arm["pose_edges"])},
       UGV_ARM_RATE_CDEG_S = {round(arm["path_rate_deg_s"] * 100)} }};
/* Poses the wheels may drive in (bit = pose number): the core refuses to drive anywhere else (DD84). */
enum {{ UGV_ARM_DRIVE_MASK = 0x{mask:02X} }};
static const int16_t UGV_ARM_POSE_CDEG[UGV_ARM_POSES][UGV_ARM_JOINTS] = {{
{rows}
}};
/* Swept edges (either direction). */
static const uint8_t UGV_ARM_EDGE[UGV_ARM_EDGES][2] = {{{edges}}};

#endif
"""


if __name__ == "__main__":
    HEADER.write_text(render(json.loads((ROOT / "config/vehicle.json").read_text())))
    print(HEADER.relative_to(ROOT))
