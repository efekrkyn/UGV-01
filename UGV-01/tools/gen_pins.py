"""Generate firmware/lite/esp32/main/pins.h from config/esp32_pinmap.json (L4a, DD86).

The ESP-IDF board layer takes every GPIO, the PCA9685 address/channel order and the ToF addresses from this header;
tests/check_esp32_pinmap.py fails when the header and the pin map disagree. `python3 tools/gen_pins.py` rewrites it.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HEADER = ROOT / "firmware/lite/esp32/main/pins.h"


def render(pinmap):
    pins = "\n".join(f"#define PIN_{a['signal']} {a['gpio']}  /* {a['peripheral']} */" for a in pinmap["assignments"])
    pca = pinmap["pca9685"]
    channels = "\n".join(f"#define PCA_CH_{name.removeprefix('SERVO_')} {k}" for k, name in enumerate(pca["channels"]))
    tof = ", ".join(pinmap["tof_addresses"])
    return f"""/* Generated by tools/gen_pins.py from config/esp32_pinmap.json: do not edit. */
#ifndef UGV_PINS_H
#define UGV_PINS_H

/* {pinmap['board']} */
{pins}

/* PCA9685 servo driver on I2C0; channel k = firmware joint k (servo_control.h). */
#define PCA9685_ADDR {pca['address']}
#define PCA9685_PWM_HZ {pca['pwm_hz']}
{channels}

/* VL53L0X front ToF pair on one XSHUT line: hold that sensor in reset, move the other from 0x29 to 0x30, then
   release XSHUT so the first wakes at 0x29. */
static const unsigned char TOF_ADDR[2] = {{{tof}}};

#endif
"""


if __name__ == "__main__":
    HEADER.write_text(render(json.loads((ROOT / "config/esp32_pinmap.json").read_text())))
    print(HEADER.relative_to(ROOT))
